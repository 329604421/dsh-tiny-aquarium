import { build } from 'esbuild';
import { mkdir, writeFile, copyFile, readFile, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
await mkdir(path.join(root, 'lib'), { recursive: true });
await mkdir(path.join(root, 'releases'), { recursive: true });

/* ------------------------------------------------------ custom asset bundles */
/*
 * P5 的定制资产在构建期内联：宿主只提供图片资源路由，`.glb` 必须走 chunk。
 * 这一步把 assets-src/models/<类别>/*.glb 变成一个静态 import 表，键名即清单 id，
 * 这样模型只写资产与清单，不需要（也不允许）改引擎代码。
 */
const CATEGORY_DIRS = { tank: 'tank', lamp: 'lamp', fish: 'fish', scene: 'scape' };
async function generateCustomBundle() {
  const imports = [];
  const entries = [];
  const ids = [];
  const models = path.join(root, 'assets-src', 'models');
  if (existsSync(models)) {
    for (const [dir, category] of Object.entries(CATEGORY_DIRS)) {
      const folder = path.join(models, dir);
      if (!existsSync(folder)) continue;
      const files = (await readdir(folder)).filter(name => name.toLowerCase().endsWith('.glb')).sort();
      for (const file of files) {
        const id = `${category}.${path.basename(file, path.extname(file))}`;
        const variable = `asset${entries.length}`;
        imports.push(`import ${variable} from '../assets-src/models/${dir}/${file}';`);
        entries.push(`  ${JSON.stringify(id)}: ${variable},`);
        ids.push(JSON.stringify(id));
      }
    }
  }
  const code = [
    '// AUTO-GENERATED by scripts/build.mjs — do not edit by hand.',
    '// 定制资产的二进制包：`npm run build` 会扫描 assets-src/models/<类别>/*.glb，',
    '// 为每个文件生成一条静态 import，键名是清单里的资产 id。',
    ...imports,
    `export const CUSTOM_BUNDLES = {${entries.length ? '\n' + entries.join('\n') + '\n' : ''}};`,
    `export const CUSTOM_BUNDLE_IDS = [${ids.join(', ')}];`,
    '',
  ].join('\n');
  await writeFile(path.join(root, 'src', 'custom-bundle.generated.js'), code);
  console.log(`custom bundle: ${entries.length} asset(s)`);
  return entries.length;
}

await generateCustomBundle();

const pluginRoot = path.resolve(root).replace(/[\\/]+$/, '');
async function bundle(entry, chunk) {
  const result = await build({
    absWorkingDir: root, entryPoints: [entry], bundle: true, write: false,
    format: 'cjs', platform: 'browser', target: 'chrome130', minify: true,
    external: ['react'], legalComments: 'inline',
    loader: { '.css': 'text', '.glb': 'binary' },
    define: {
      'process.env.NODE_ENV': '"production"',
      __AQ_PLUGIN_ROOT__: JSON.stringify(pluginRoot),
    },
  });
  const registration = chunk ? `,chunk:${JSON.stringify(chunk)}` : '';
  const code = `window.__ModuleLoader__.load({id:"dsh-eco-aquarium"${registration},factory(require){const module={exports:{}};const exports=module.exports;\n${result.outputFiles[0].text}\nreturn module.exports;}});\n`;
  await writeFile(path.join(root, 'lib', chunk || 'client.js'), code);
  console.log(`${chunk || 'client.js'}: ${Buffer.byteLength(code)} bytes`);
}
// Write the entry last: the host derives the whole generation from its metadata.
await bundle('src/scene.js', 'client.scene.js');
await bundle('src/client.jsx');
await copyFile(path.join(root, 'src/host.js'), path.join(root, 'lib/host.js'));
await copyFile(path.join(root, 'node_modules/three/LICENSE'), path.join(root, 'lib/THREE-LICENSE.txt'));
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
await writeFile(path.join(root, 'lib/build-info.json'), JSON.stringify({
  version: pkg.version, three: pkg.devDependencies.three, hostBaseline: '0.2.2-rc.3', pluginRoot,
}, null, 2));
